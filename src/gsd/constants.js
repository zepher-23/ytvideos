// Deterministic color generator for any arbitrary person name
export const getPersonColor = (name) => {
  if (PERSON_COLORS[name]) return PERSON_COLORS[name];
  // Generate consistent vibrant HSL color from name hash
  let hash = 0;
  for (let i = 0; i < name.length; i++) {
    hash = name.charCodeAt(i) + ((hash << 5) - hash);
  }
  const hue = Math.abs(hash) % 360;
  return {
    primary: `hsl(${hue}, 80%, 45%)`,
    light: `hsl(${hue}, 85%, 62%)`,
    text: "#FFFFFF",
  };
};

